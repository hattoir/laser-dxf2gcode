"""G-code 生成(GRBL / Creality Falcon2)と、生成後の安全検証。

安全のための三段構え
    1. 生成前: 全座標(リードイン・待機位置を含む)が加工エリア内かを検査。
       1 点でも外れたら WorkAreaError(G-code は 1 行も返さない)
    2. 生成: ヘッダで G21 G90 G94 / M5 / S0 / 原点付近へ G0 S0。
       各輪郭は「G0 ... S0 → M4 S<p> → G1 ... → M5」。末尾は必ず M5
    3. 生成後: 出来上がったテキストを独立したパーサで読み直し、規則違反
       (G0 に S0 が無い、発振中の G0、M3 の使用、範囲外座標、末尾 M5 欠落など)
       があれば GcodeSafetyError。プレビューも同じパーサの結果から描く
       ので、「見た絵」と「流すコード」が食い違わない
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from datetime import datetime
from typing import Iterable, Sequence

from .config import Machine
from .errors import GcodeSafetyError, WorkAreaError
from .geometry import Point
from .toolpath import CutPath, Plan

COORD_DECIMALS = 3
ALLOWED_G = {0, 1, 21, 90, 94}
ALLOWED_M = {4, 5, 8, 9}
PASS_MODES = ("path", "cycle")


def fmt(v: float) -> str:
    s = f"{round(v, COORD_DECIMALS):.{COORD_DECIMALS}f}"
    return "0.000" if s == "-0.000" else s


def rounded(v: float) -> float:
    return float(fmt(v))


def ascii_comment(text: str) -> str:
    """G-code のコメントは ASCII に限る(送信ソフトやファームが非 ASCII で誤動作しうる)。"""
    return "".join(ch if 32 <= ord(ch) < 127 and ch not in "()" else "?" for ch in text)


def power_to_s(percent: float, s_max: int, warnings: list[str] | None = None, where: str = "") -> int:
    """出力 % → S 値。0〜s_max にクランプする。"""
    s = round(percent / 100.0 * s_max)
    if s < 0 or s > s_max:
        clamped = min(max(s, 0), s_max)
        if warnings is not None:
            warnings.append(f"出力 {percent}% は範囲外のため S{clamped} にクランプしました {where}".rstrip())
        s = clamped
    return int(s)


# --------------------------------------------------------------------------
# 1. 加工エリア検査
# --------------------------------------------------------------------------

@dataclass
class AreaViolation:
    x: float
    y: float
    path_index: int | None
    description: str


def find_area_violations(paths: Sequence[CutPath], machine: Machine,
                         extra_points: Iterable[tuple[Point, str]] = ()) -> list[AreaViolation]:
    """0 <= X <= x_max, 0 <= Y <= y_max を外れる点を列挙する(G-code に書かれる桁で判定)。"""
    out = []

    def bad(x, y):
        x, y = rounded(x), rounded(y)
        return x < 0 or y < 0 or x > machine.x_max or y > machine.y_max

    for (x, y), desc in extra_points:
        if bad(x, y):
            out.append(AreaViolation(x, y, None, desc))
    for i, p in enumerate(paths):
        for x, y in p.points:
            if bad(x, y):
                out.append(AreaViolation(x, y, i, f"path #{i + 1} layer='{p.layer}' role={p.role} {p.source}"))
    return out


def check_work_area(paths: Sequence[CutPath], machine: Machine,
                    extra_points: Iterable[tuple[Point, str]] = ()) -> None:
    v = find_area_violations(paths, machine, extra_points)
    if not v:
        return
    lines = [f"加工エリア (0<=X<={machine.x_max}, 0<=Y<={machine.y_max}) の外の座標が {len(v)} 点あります。"
             "G-code は出力しません。"]
    seen = set()
    for a in v:
        if a.description in seen:
            continue
        seen.add(a.description)
        lines.append(f"  X={a.x:.3f} Y={a.y:.3f}  ← {a.description}")
        if len(seen) >= 10:
            lines.append("  ...")
            break
    xs = [a.x for a in v]
    ys = [a.y for a in v]
    lines.append(f"  範囲外の点の広がり: X {min(xs):.3f}〜{max(xs):.3f}, Y {min(ys):.3f}〜{max(ys):.3f}")
    lines.append("  対処: DXF の原点を見直すか、--align lower-left / --offset DX DY で配置してください")
    raise WorkAreaError("\n".join(lines))


